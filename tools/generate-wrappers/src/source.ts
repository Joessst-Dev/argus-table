// Helpers shared by the framework emitters.
import { referencedTypes, type ElementInfo } from './manifest.ts';

/** The comment at the top of every generated module. */
export function header(framework: string): string {
  return `// Generated by tools/generate-wrappers from argus-table's Custom Elements Manifest.
// Don't edit by hand: run \`pnpm --filter @argus-table/${framework} generate\`.`;
}

/** One line of JSDoc: the description, without line breaks or a closing comment. */
export function doc(text: string): string {
  return text.replace(/\s+/g, ' ').replaceAll('*/', '*\\/').trim();
}

/** The types the elements' events refer to, sorted, for an import from `argus-table`. */
export function eventTypes(elements: readonly ElementInfo[]): string[] {
  const types = new Set<string>();
  for (const el of elements) {
    for (const e of el.events) for (const t of referencedTypes(e.type)) types.add(t);
  }
  return [...types].sort();
}
