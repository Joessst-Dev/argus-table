// Helpers shared by the framework emitters.
import { referencedTypes, type ElementInfo } from './manifest.ts';

/** The comment at the top of every generated module. */
export function header(framework: string): string {
  return `// Generated by tools/generate-wrappers from argus-table's Custom Elements Manifest.
// Don't edit by hand: run \`pnpm --filter @argus-table/${framework} generate\`.`;
}

/** One line of JSDoc: the description, without line breaks or a closing comment. */
export function doc(text: string): string {
  return text.replace(/\s+/g, ' ').replaceAll('*/', '*\\/').trim();
}

/**
 * Content properties' types in a framework's wrapper, by property name. `null`:
 * the wrapper sets the property itself and leaves it out (`contentRenderer`).
 */
export type ContentTypes = Readonly<Record<string, string | null>>;

/** Whether an element renders content: the wrapper then gives it a content renderer. */
export const rendersContent = (el: ElementInfo): boolean =>
  el.properties.some((p) => p.name === 'contentRenderer');

/** A content property's type; the row type is `unknown` for an element that isn't generic. */
export function contentType(types: ContentTypes, property: string, generic: boolean): string {
  const type = types[property] ?? 'unknown';
  return generic ? type : type.replace(/\bT\b/g, 'unknown');
}

/** Whether an element takes `columnGroups`: the wrapper then imports its group type. */
export const usesGroups = (elements: readonly ElementInfo[]): boolean =>
  elements.some((el) => el.properties.some((p) => p.name === 'columnGroups'));

/** Whether any element has a property typed for the framework's content. */
export const usesContentTypes = (elements: readonly ElementInfo[], types: ContentTypes): boolean =>
  elements.some((el) => el.properties.some((p) => typeof types[p.name] === 'string'));

/**
 * The types to import from `argus-table`, sorted: the ones the elements' events
 * refer to and, with content, `CellContext`.
 */
export function argusTypes(elements: readonly ElementInfo[], withContent: boolean): string[] {
  const types = new Set<string>();
  for (const el of elements) {
    for (const e of el.events) {
      if (e.from === undefined) for (const t of referencedTypes(e.type)) types.add(t);
    }
  }
  if (withContent) types.add('CellContext');
  return [...types].sort();
}

/**
 * `import type` lines for add-on events' types, from the wrapper's own modules
 * (`ADDON_EVENTS`), sorted by module.
 */
export function addonTypeImports(elements: readonly ElementInfo[]): string {
  const modules = new Map<string, Set<string>>();
  for (const el of elements) {
    for (const e of el.events) {
      if (e.from === undefined) continue;
      const types = modules.get(e.from) ?? new Set();
      for (const t of referencedTypes(e.type)) types.add(t);
      modules.set(e.from, types);
    }
  }
  return [...modules]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([from, types]) => `import type { ${[...types].sort().join(', ')} } from '${from}';\n`)
    .join('');
}
